// Rasterises components/images/graphic_design/Magazine_Demo.pdf into compressed
// web JPEGs (public/media/graphic_design/magazine/) and writes a page manifest.
//
//   node scripts/gen-flipbook.mjs
//
// Wired to predev/prebuild.
import { pdf } from "pdf-to-img";
import sharp from "sharp";
import fs from "fs";
import path from "path";

const ROOT = process.cwd();
const PDF = path.join(ROOT, "components", "images", "graphic_design", "Magazine_Demo.pdf");
const OUT = path.join(ROOT, "public", "media", "graphic_design", "magazine");
const MANIFEST = path.join(ROOT, "lib", "flipbook.generated.ts");

if (!fs.existsSync(PDF)) {
  // No magazine source — emit an empty manifest so the import always resolves.
  fs.writeFileSync(
    MANIFEST,
    `/* eslint-disable */\n// AUTO-GENERATED by scripts/gen-flipbook.mjs — DO NOT EDIT.\nexport interface FlipPage { src: string; }\nexport const magazine = { width: 0, height: 0, pages: [] as FlipPage[] };\n`
  );
  console.log("flipbook: no Magazine_Demo.pdf, wrote empty manifest");
  process.exit(0);
}

fs.mkdirSync(OUT, { recursive: true });
// Clean previously generated pages.
for (const f of fs.readdirSync(OUT)) {
  if (/^page-\d+\.jpg$/.test(f)) fs.unlinkSync(path.join(OUT, f));
}

// Final width of each individual flipbook page (after splitting spreads).
// ~880px is plenty: fullscreen shows each page at roughly 640px, inline ~500px.
const PAGE_W = 880;

// The source PDF mixes single portrait pages (front/back cover) with landscape
// pages that each hold a full TWO-PAGE spread (left + right page side by side).
// page-flip expects one image per individual page, so we split every landscape
// spread down the middle into a left and a right page; portrait pages are kept
// whole. Rendered at a high scale so each half still has plenty of resolution.
const doc = await pdf(PDF, { scale: 4 });
let i = 0; // output (individual) page counter
let width = 0;
let height = 0;
const pages = [];

const emit = async (img) => {
  i++;
  const name = `page-${String(i).padStart(3, "0")}.jpg`;
  const buf = await sharp(img)
    .resize({ width: PAGE_W, withoutEnlargement: true })
    .jpeg({ quality: 74, mozjpeg: true })
    .toBuffer();
  fs.writeFileSync(path.join(OUT, name), buf);
  if (i === 1) {
    const m = await sharp(buf).metadata();
    width = m.width;
    height = m.height;
  }
  pages.push(`  { src: "/media/graphic_design/magazine/${name}" }`);
};

for await (const page of doc) {
  const img = sharp(page);
  const m = await img.metadata();
  if (m.width > m.height) {
    // Landscape => two-page spread. Split into left and right halves.
    const half = Math.floor(m.width / 2);
    const left = await sharp(page).extract({ left: 0, top: 0, width: half, height: m.height }).toBuffer();
    const right = await sharp(page)
      .extract({ left: m.width - half, top: 0, width: half, height: m.height })
      .toBuffer();
    await emit(left);
    await emit(right);
  } else {
    // Portrait => single page (cover / back cover).
    await emit(page);
  }
}

const ts =
  `/* eslint-disable */\n` +
  `// AUTO-GENERATED by scripts/gen-flipbook.mjs — DO NOT EDIT.\n` +
  `export interface FlipPage { src: string; }\n` +
  `export const magazine = {\n  width: ${width},\n  height: ${height},\n  pages: [\n${pages.join(
    ",\n"
  )}\n  ] as FlipPage[],\n};\n`;
fs.writeFileSync(MANIFEST, ts);
console.log(`flipbook: ${i} pages, ${width}x${height}`);
